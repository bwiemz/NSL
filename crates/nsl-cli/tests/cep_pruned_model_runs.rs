//! CEP end to end: the pruned source and the pruned weights load and run
//! together, and compute what the unpruned model computed.
//!
//! The chain is the one a user follows, with no hand repair in between:
//!
//!   1. an NSL program builds the model and `model_save`s it;
//!   2. `nsl build --cep-prune --weights base.nslm --cep-emit-weights
//!      pruned.nslm --cep-emit-source pruned.nsl`;
//!   3. the emitted program `model_load`s the emitted weights and runs.
//!
//! The weights are chosen so that the right answer is known. In each layer
//! one key/value group of heads has a zero output projection and eight FFN
//! neurons have a zero `w_down` row: those components contribute exactly
//! nothing, the sparsity target is exactly what removing them removes, and so
//! the pruned model must reproduce the unpruned model's output. Every other
//! choice changes it:
//!
//!   * the dead neurons have gate columns ten times larger than the live
//!     ones, so ranking by `w_gate` alone keeps them and drops live neurons;
//!   * layer 0's first four residual features are scaled by 1e-3 in `wq`,
//!     `wk` and `wv`, so a scorer that cuts those three along their input
//!     axis and never reads `wo` (what CEP used to do) sees a weak "head 0"
//!     that is not a head at all, and removes live heads;
//!   * the dead heads are a different group in each layer;
//!   * the attention reshapes by head counts stored in the checkpoint, so
//!     weights sliced without rewriting them do not run at all.
//!
//! The reference output is not NSL's. The three checksums below come from a
//! float64 NumPy implementation of the same model (RMSNorm, grouped-query
//! attention with rotary positions and a causal mask, SwiGLU) applied to the
//! same weights, generated by the same integer formula as `fill` here.

use std::path::{Path, PathBuf};
use std::process::Command;

use assert_cmd::prelude::*;
use nsl_codegen::cep_weights::{load_weights, write_nslm};
use nsl_codegen::weight_aware::{WeightDType, WeightEntry};

fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .parent()
        .unwrap()
        .to_path_buf()
}

const D: usize = 16;
const HEAD_DIM: usize = 4;
const N_HEADS: usize = 4;
const N_KV: usize = 2;
const D_FF: usize = 32;

/// NumPy float64 reference for the unpruned model on the input below:
/// `sum(y)`, `sum(y²)` and `sum(y_i · i)` over the 128 output values.
const REF_SUM: f64 = 1.321_059_384;
const REF_SUM_SQ: f64 = 118.664_003_677;
const REF_WEIGHTED: f64 = -159.523_022_601;

/// The model. `{TAIL}` is what the program does with it.
const MODEL: &str = r#"from nsl.nn.norms import RMSNorm
from nsl.nn.gqa import GroupedQueryAttention

model SwiGLUFFN(d_model: int, d_ff: int, dropout_p: float):
    w_gate: Tensor = randn([d_model, d_ff])
    w_up: Tensor = randn([d_model, d_ff])
    w_down: Tensor = randn([d_ff, d_model])

    fn forward(self, x: Tensor) -> Tensor:
        let gate = silu(x @ self.w_gate)
        let up = x @ self.w_up
        return (gate * up) @ self.w_down

model TransformerBlock(d_model: int, n_heads: int, n_kv_heads: int, head_dim: int, d_ff: int, dropout_p: float, max_seq_len: int, rope_theta: float, n_layers: int):
    attn_norm: RMSNorm = RMSNorm(d_model)
    attn: GroupedQueryAttention = GroupedQueryAttention(d_model, n_heads, n_kv_heads, head_dim, dropout_p, max_seq_len, rope_theta, n_layers)
    ffn_norm: RMSNorm = RMSNorm(d_model)
    ffn: SwiGLUFFN = SwiGLUFFN(d_model, d_ff, dropout_p)

    fn forward(self, x: Tensor) -> Tensor:
        let h = x + self.attn.forward(self.attn_norm.forward(x), false)
        return h + self.ffn.forward(self.ffn_norm.forward(h))

@cep_prune(target = h100, sparsity = 0.29, granularity = "head+ffn")
model TinyCoder:
    embed: Tensor = randn([32, 16])
    blocks: [TransformerBlock; 2] = TransformerBlock(16, 4, 2, 4, 32, 0.0, 8, 10000.0, 2)
    norm: RMSNorm = RMSNorm(16)

    fn forward(self, x: Tensor) -> Tensor:
        let h = x
        for block in self.blocks:
            h = block.forward(h)
        return self.norm.forward(h)

let m = TinyCoder()
{TAIL}
"#;

const SAVE: &str = r#"model_save(m, "init.nslm")"#;

/// Load the weights, run one forward on a fixed input, print the checksums
/// scaled so the default float formatting keeps the digits that matter.
const RUN: &str = r#"model_load(m, "WEIGHTS_FILE")
let x: Tensor = tensor_sin(arange(0.0, 128.0) * 0.37).reshape([1, 8, 16])
let y: Tensor = m.forward(x)
let flat: Tensor = y.reshape([128])
let s1: Tensor = flat.sum()
let s2: Tensor = (flat * flat).sum()
let s3: Tensor = (flat * arange(0.0, 128.0)).sum()
print("CHECKSUM")
print(s1.item() * 1000000.0)
print(s2.item() * 1000000.0)
print(s3.item() * 1000000.0)
"#;

fn nsl(dir: &Path) -> Command {
    let mut cmd = Command::cargo_bin("nsl").unwrap();
    cmd.env("NSL_STDLIB_PATH", workspace_root().join("stdlib"))
        .current_dir(dir);
    cmd
}

fn run_program(dir: &Path, file: &Path) -> String {
    let out = nsl(dir)
        .arg("run")
        .arg(file)
        .arg("--target")
        .arg("cpu")
        .output()
        .unwrap();
    assert!(
        out.status.success(),
        "`nsl run {}` failed:\nstdout:\n{}\nstderr:\n{}",
        file.display(),
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr)
    );
    String::from_utf8_lossy(&out.stdout).into_owned()
}

/// The three numbers printed after the `CHECKSUM` marker, unscaled.
fn checksums(stdout: &str) -> [f64; 3] {
    let mut lines = stdout
        .lines()
        .skip_while(|l| l.trim() != "CHECKSUM")
        .skip(1);
    let mut next = || -> f64 {
        let line = lines
            .next()
            .unwrap_or_else(|| panic!("missing checksum line in:\n{stdout}"));
        line.trim()
            .parse::<f64>()
            .unwrap_or_else(|_| panic!("not a number: '{line}'"))
            / 1e6
    };
    [next(), next(), next()]
}

fn assert_matches_reference(what: &str, got: [f64; 3]) {
    // f32 arithmetic against a float64 reference: a few parts in 1e5 of the
    // magnitudes summed. A wrongly chosen head or neuron moves every one of
    // these by orders of magnitude more.
    let checks = [
        ("sum", got[0], REF_SUM, 2e-3),
        ("sum of squares", got[1], REF_SUM_SQ, 2e-2),
        ("weighted sum", got[2], REF_WEIGHTED, 1e-1),
    ];
    for (name, g, want, tol) in checks {
        assert!(
            (g - want).abs() <= tol,
            "{what}: {name} is {g}, the reference is {want}"
        );
    }
}

/// `((i·7919 + k·104729 + 12345) mod 2003) / 2003 − 0.5`, times `scale`:
/// exact in float64, so NumPy and this agree bit for bit after the cast.
fn fill(n: usize, k: u64, scale: f64) -> Vec<f32> {
    (0..n as u64)
        .map(|i| {
            ((((i * 7919 + k * 104_729 + 12_345) % 2003) as f64 / 2003.0 - 0.5) * scale) as f32
        })
        .collect()
}

fn f32_entry(name: &str, shape: Vec<usize>, vals: &[f32]) -> WeightEntry {
    assert_eq!(vals.len(), shape.iter().product::<usize>(), "{name}");
    let data: Vec<u8> = vals.iter().flat_map(|v| v.to_le_bytes()).collect();
    WeightEntry::new(name.to_string(), data, shape, WeightDType::F32)
}

/// The weights of layer `l`, by path inside the block.
fn layer_weights(l: usize) -> Vec<(&'static str, Vec<usize>, Vec<f32>)> {
    let k = 10 * l as u64;
    let q_cols = N_HEADS * HEAD_DIM;
    let kv_cols = N_KV * HEAD_DIM;
    let mut wq = fill(D * q_cols, k, 0.5);
    let mut wk = fill(D * kv_cols, k + 1, 0.5);
    let mut wv = fill(D * kv_cols, k + 2, 0.5);
    let mut wo = fill(q_cols * D, k + 3, 0.5);
    let mut gate = fill(D * D_FF, k + 4, 0.5);
    let up = fill(D * D_FF, k + 5, 0.5);
    let mut down = fill(D_FF * D, k + 6, 0.5);
    let attn_norm: Vec<f32> = fill(D, k + 7, 0.4).iter().map(|v| 1.0 + v).collect();
    let ffn_norm: Vec<f32> = fill(D, k + 8, 0.4).iter().map(|v| 1.0 + v).collect();

    // One dead key/value group: its two query heads write nothing (their rows
    // of `wo` are zero). Group 1 (heads 2, 3) in layer 0, group 0 in layer 1.
    let dead_group = if l == 0 { 1 } else { 0 };
    let rows = dead_group * 2 * HEAD_DIM..(dead_group + 1) * 2 * HEAD_DIM;
    for r in rows {
        wo[r * D..(r + 1) * D].fill(0.0);
    }
    // Eight dead FFN neurons, with large gates: a zero `w_down` row.
    let dead_residue = if l == 0 { 0 } else { 3 };
    for j in (0..D_FF).filter(|j| j % 4 == dead_residue) {
        down[j * D..(j + 1) * D].fill(0.0);
        for r in 0..D {
            gate[r * D_FF + j] *= 10.0;
        }
    }
    // Layer 0: residual features 0..4 are barely read by the attention.
    if l == 0 {
        for (m, cols) in [(&mut wq, q_cols), (&mut wk, kv_cols), (&mut wv, kv_cols)] {
            for v in &mut m[0..4 * cols] {
                *v *= 1e-3;
            }
        }
    }
    vec![
        ("attn.wq", vec![D, q_cols], wq),
        ("attn.wk", vec![D, kv_cols], wk),
        ("attn.wv", vec![D, kv_cols], wv),
        ("attn.wo", vec![q_cols, D], wo),
        ("ffn.w_gate", vec![D, D_FF], gate),
        ("ffn.w_up", vec![D, D_FF], up),
        ("ffn.w_down", vec![D_FF, D], down),
        ("attn_norm.weight", vec![D], attn_norm),
        ("ffn_norm.weight", vec![D], ffn_norm),
    ]
}

/// Replace the model's randomly initialised weights in `init` (as NSL's own
/// `model_save` wrote it: names, order, stored scalars and rotary tables
/// untouched) with the deterministic ones, and write `base`.
fn write_base_checkpoint(init: &Path, base: &Path) {
    let mut w = load_weights(init).expect("the checkpoint model_save wrote");
    let mut replaced = 0;
    let mut put =
        |w: &mut nsl_codegen::cep_weights::CepWeights, name: String, shape, vals: &[f32]| {
            let old = w
                .map
                .get(&name)
                .unwrap_or_else(|| panic!("model_save wrote no '{name}'"));
            assert_eq!(old.shape, shape, "{name}");
            w.map.insert(f32_entry(&name, shape, vals));
            replaced += 1;
        };
    for l in 0..2 {
        for (rest, shape, vals) in layer_weights(l) {
            put(&mut w, format!("blocks[{l}].{rest}"), shape, &vals);
        }
    }
    let norm: Vec<f32> = fill(D, 100, 0.4).iter().map(|v| 1.0 + v).collect();
    put(&mut w, "norm.weight".to_string(), vec![D], &norm);
    put(
        &mut w,
        "embed".to_string(),
        vec![32, D],
        &fill(32 * D, 101, 0.5),
    );
    assert_eq!(replaced, 20);
    let ordered: Vec<&WeightEntry> = w.order.iter().map(|n| w.map.get(n).unwrap()).collect();
    write_nslm(&ordered, base).unwrap();
}

#[test]
fn pruned_source_and_weights_run_and_match_the_unpruned_model() {
    let tmp = tempfile::tempdir().unwrap();
    let dir = tmp.path();

    // 1. Let NSL write the checkpoint, so its names, order and stored
    //    configuration tensors are the toolchain's own.
    let save = dir.join("save.nsl");
    std::fs::write(&save, MODEL.replace("{TAIL}", SAVE)).unwrap();
    run_program(dir, &save);
    write_base_checkpoint(&dir.join("init.nslm"), &dir.join("base.nslm"));

    // The unpruned model on these weights reproduces the NumPy reference:
    // the reference describes this model, and the checkpoint was read as
    // intended.
    let base = dir.join("base.nsl");
    std::fs::write(
        &base,
        MODEL.replace("{TAIL}", &RUN.replace("WEIGHTS_FILE", "base.nslm")),
    )
    .unwrap();
    assert_matches_reference("unpruned model", checksums(&run_program(dir, &base)));

    // 2. Prune. 29% of the model's 5,200 parameters is 1,508; the dead
    //    components are 2·(384 + 384) = 1,536, and no smaller set reaches it.
    let out = nsl(dir)
        .arg("build")
        .arg(&base)
        .arg("--cep-prune")
        .arg("--weights")
        .arg("base.nslm")
        .arg("--cep-out")
        .arg("delta.json")
        .arg("--cep-emit-weights")
        .arg("pruned.nslm")
        .arg("--cep-emit-source")
        .arg("pruned_emitted.nsl")
        .output()
        .unwrap();
    let stdout = String::from_utf8_lossy(&out.stdout);
    assert!(
        out.status.success(),
        "--cep-prune failed:\n{stdout}\n{}",
        String::from_utf8_lossy(&out.stderr)
    );
    assert!(
        stdout.contains("Sparsity target and constraints met."),
        "{stdout}"
    );

    // The plan removed exactly the dead components.
    let v: serde_json::Value =
        serde_json::from_str(&std::fs::read_to_string(dir.join("delta.json")).unwrap()).unwrap();
    let layer = |l: usize| &v["delta"]["per_layer"][l];
    assert_eq!(
        layer(0)["pruned_heads"],
        serde_json::json!([2, 3]),
        "layer 0's dead group"
    );
    assert_eq!(
        layer(1)["pruned_heads"],
        serde_json::json!([0, 1]),
        "layer 1's dead group"
    );
    assert_eq!(layer(0)["new_d_ff"], 24);
    assert_eq!(layer(1)["new_d_ff"], 24);
    assert_eq!(v["baseline_profile"]["param_bytes"], 5_200 * 4);
    assert_eq!(v["chosen"]["profile"]["param_bytes"], (5_200 - 1_536) * 4);

    // 3. The emitted program, pointed at the emitted weights.
    let emitted = std::fs::read_to_string(dir.join("pruned_emitted.nsl")).unwrap();
    assert!(
        emitted.contains("TransformerBlock(16, 2, 1, 4, 24, 0.0, 8, 10000.0, 2)"),
        "the emitted block constructor:\n{emitted}"
    );
    assert!(emitted.contains(r#"model_load(m, "base.nslm")"#));
    let pruned = dir.join("pruned.nsl");
    std::fs::write(&pruned, emitted.replace("base.nslm", "pruned.nslm")).unwrap();
    assert_matches_reference("pruned model", checksums(&run_program(dir, &pruned)));
}
