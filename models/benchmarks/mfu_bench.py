#!/usr/bin/env python3
"""Measure pretraining throughput and model-FLOPs utilisation for NSL-Coder-50M.

Generates a small NSL training program per configuration, runs it, and converts
the observed step time into tokens/s and MFU.

MFU is reported against the *dense* tensor throughput of the device for the
precision actually in use, selected per device from PEAK_TFLOPS_BY_DEVICE
(auto-detected via nvidia-smi; override with --gpu-name). The table matters:
on GeForce Blackwell (RTX 5070 Ti) the TF32 tensor rate is capped at the FP32
vector rate, while the workstation RTX PRO 4500 (same GB203 silicon) runs
TF32 at 2.4x and BF16 at 2.8x the GeForce figures — measured, not whitepaper.
An MFU% computed against the wrong card's peak is off by that same factor.
Reporting against the marketed "AI TOPS" figure would understate utilisation
by 16x, since that number is FP4 with 2:4 sparsity.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import statistics
import subprocess
import sys
import threading
import time
from dataclasses import dataclass
from pathlib import Path

# Dense TFLOPS per device. Keys must match `nvidia-smi --query-gpu=name` output.
# 5070 Ti: RTX Blackwell whitepaper App. B. RTX PRO 4500: measured 2026-07-30
# with a cuBLAS GemmEx probe at N=8192 (fp32/tf32/bf16/fp16 sustained at the
# 200 W limit, 2535 MHz); its fp8 entry is the 2x-of-BF16 dense ratio the
# whitepaper gives for every Blackwell part, not a direct measurement.
PEAK_TFLOPS_BY_DEVICE = {
    "NVIDIA GeForce RTX 5070 Ti": {
        "fp32": 43.9,
        "tf32": 43.9,  # equal to FP32 vector on GeForce — TF32 is not a free 2x
        "bf16": 87.9,
        "fp16": 87.9,
        "fp8": 175.8,
    },
    "NVIDIA RTX PRO 4500 Blackwell": {
        "fp32": 36.5,
        "tf32": 87.6,  # workstation GB203 is NOT GeForce-capped
        "bf16": 200.3,
        "fp16": 199.8,
        "fp8": 400.6,  # 2x bf16 dense ratio, unmeasured
    },
}
PRECISIONS = sorted(PEAK_TFLOPS_BY_DEVICE["NVIDIA GeForce RTX 5070 Ti"])
assert all(sorted(v) == PRECISIONS for v in PEAK_TFLOPS_BY_DEVICE.values()), \
    "every device entry must cover the same precision set"

MEMORY_BW_GB_S = 896.0  # 256-bit GDDR7 @ 28 Gbps — same on both GB203 cards


def detect_gpu_name() -> str:
    """First GPU name from nvidia-smi, or empty string if unavailable."""
    try:
        out = subprocess.run(
            ["nvidia-smi", "--query-gpu=name", "--format=csv,noheader"],
            capture_output=True, text=True, timeout=10, check=True,
        ).stdout
        return out.strip().splitlines()[0].strip() if out.strip() else ""
    except (OSError, subprocess.SubprocessError):
        return ""


@dataclass(frozen=True)
class ModelShape:
    n_layers: int = 8
    d_model: int = 512
    n_heads: int = 8
    n_kv_heads: int = 4
    head_dim: int = 64
    d_ff: int = 1408
    vocab_size: int = 49152
    tied_embeddings: bool = True

    def matmul_params(self) -> int:
        """Parameters that participate in a matmul for every token.

        The input embedding is a gather, not a matmul, so it is excluded; the
        output projection is included even when the weights are tied, because
        the matmul still runs.
        """
        attn = (
            self.d_model * self.n_heads * self.head_dim  # q
            + 2 * self.d_model * self.n_kv_heads * self.head_dim  # k, v
            + self.n_heads * self.head_dim * self.d_model  # o
        )
        ffn = 3 * self.d_model * self.d_ff  # SwiGLU: gate, up, down
        per_layer = attn + ffn
        head = self.d_model * self.vocab_size
        return self.n_layers * per_layer + head

    def flops_per_token(self, seq_len: int) -> float:
        """Forward+backward model FLOPs per token.

        6*N covers one multiply-add forward and two backward, doubled for the
        multiply-add. The second term is attention's score and value matmuls,
        which scale with sequence length and are not captured by parameter
        count. Halved for causal masking, which is what actually runs.
        """
        dense = 6.0 * self.matmul_params()
        attn = 6.0 * self.n_layers * self.n_heads * self.head_dim * seq_len
        return dense + attn


TEMPLATE = """\
# Generated by models/benchmarks/mfu_bench.py — do not edit.
from model import NSLCoder
from nsl.nn.losses import cross_entropy

let m = NSLCoder()
m.to(cuda)

let tokens = load_mmap("{tokens_path}", 3)
let loader = DataLoader(tokens, batch_size={batch_size}, seq_len={seq_len}, shuffle=false, drop_last=true)

{decorator}train(model=m, epochs=1, grad_clip={grad_clip}{accum_arg}{extra_train_args}):
    optimizer: AdamW(lr=0.0003, weight_decay=0.1, beta1=0.9, beta2=0.95)
    scheduler: warmup_cosine(warmup_steps=100, total_steps=100000, min_lr=0.00003)
    step(batch):
        let logits = m.forward_train(batch.input_ids, true)
        let flat_logits = logits.reshape([{rows}, {vocab}])
        let flat_labels = batch.labels.reshape([{rows}])
        let loss = cross_entropy(flat_logits, flat_labels)
    callbacks:
        on_step(step, loss):
            print(step)
"""
# NOTE: the flatten uses COMPILE-TIME dims, not `logits.shape`. Under
# @fused_lm_ce a runtime `.shape` read of the logits is a live consumer of
# the composite chain and the compiler (correctly) hard-refuses: it would
# force the [rows, vocab] logits to materialize every step, defeating the
# fusion. The dims are known here anyway — the decorator requires them.


def build_program(
    out_dir: Path, tokens_path: Path, batch_size: int, seq_len: int, grad_clip: float, extra: str,
    grad_accum: int, fused_ce: bool, shape: "ModelShape",
) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    decorator = ""
    if fused_ce:
        decorator = (
            f"@fused_lm_ce(enabled=true, vocab_size={shape.vocab_size}, "
            f"hidden_size={shape.d_model}, batch_size={batch_size}, "
            f"seq_len={seq_len})\n"
        )
    # The program imports `model`, so it has to sit beside model.nsl.
    src = TEMPLATE.format(
        tokens_path=tokens_path.as_posix(),
        batch_size=batch_size,
        seq_len=seq_len,
        grad_clip=grad_clip,
        accum_arg=f", grad_accumulation={grad_accum}" if grad_accum > 1 else "",
        extra_train_args=extra,
        decorator=decorator,
        rows=batch_size * seq_len,
        vocab=shape.vocab_size,
    )
    path = out_dir / "mfu_generated.nsl"
    path.write_text(src, encoding="utf-8")
    return path


STEP_RE = re.compile(r"^\s*(\d+)\s*$")


def run_once(
    nsl: Path, program: Path, env_extra: dict[str, str], timeout: int, max_steps: int,
    flags: list[str],
) -> tuple[list[float], str]:
    """Run the program, timing the interval between step callbacks."""
    env = dict(os.environ)
    env.update(env_extra)
    env.setdefault("NSL_STDLIB_PATH", str(Path(__file__).resolve().parents[2] / "stdlib"))

    started = time.monotonic()
    proc = subprocess.Popen(
        [str(nsl), "run", *flags, str(program.name)],
        cwd=program.parent,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        env=env,
        bufsize=1,
    )

    stamps: list[float] = []
    output: list[str] = []
    assert proc.stdout is not None

    # The reader runs on a thread so the timeout is enforced by the main thread.
    # Checking the deadline inside `for line in proc.stdout` only works while the
    # child keeps talking: the iterator blocks in read(), so a run that hangs
    # before its first step callback — an OOM retry loop, a cuCtxSynchronize
    # deadlock, a compile that never finishes — never evaluated the check and
    # blocked forever instead of reporting a FAILED row.
    def reader() -> None:
        assert proc.stdout is not None
        for line in proc.stdout:
            output.append(line)
            if STEP_RE.match(line):
                stamps.append(time.monotonic())
                if len(stamps) >= max_steps:
                    break

    pump = threading.Thread(target=reader, daemon=True)
    pump.start()
    try:
        while pump.is_alive():
            if time.monotonic() - started > timeout:
                break
            pump.join(timeout=0.5)
    finally:
        proc.terminate()
        try:
            proc.wait(timeout=20)
        except subprocess.TimeoutExpired:
            proc.kill()
        # Terminating the child closes the pipe, which ends the reader.
        pump.join(timeout=10)

    deltas = [b - a for a, b in zip(stamps, stamps[1:])]
    return deltas, "".join(output)


def main() -> None:
    repo = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--nsl", type=Path, default=repo / "target/release/nsl")
    parser.add_argument("--model-dir", type=Path, default=repo / "models/coder50m")
    parser.add_argument("--tokens", type=Path, default=repo / "data/tokens/train_new.bin")
    parser.add_argument("--batch-sizes", type=int, nargs="+", default=[1])
    parser.add_argument("--seq-len", type=int, default=1024)
    parser.add_argument("--grad-clip", type=float, default=1.0)
    parser.add_argument("--grad-accum", type=int, default=1)
    parser.add_argument("--precision", default="tf32", choices=PRECISIONS)
    parser.add_argument("--gpu-name", default=None,
                        help="device key for PEAK_TFLOPS_BY_DEVICE (default: auto-detect\n"
                             "via nvidia-smi; the run refuses an unknown device rather than\n"
                             "report an MFU% against the wrong roofline)")
    parser.add_argument("--extra-train-args", default="")
    parser.add_argument("--env", action="append", default=[], help="KEY=VALUE passed to the run")
    parser.add_argument("--max-steps", type=int, default=25)
    parser.add_argument("--timeout", type=int, default=900)
    parser.add_argument("--json-out", type=Path)
    parser.add_argument("--label", default="baseline")
    parser.add_argument("--flags", default="--source-ad",
                        help="flags passed to `nsl run` (default: --source-ad, which is the\nonly path with flash attention and fused cross-entropy)")
    parser.add_argument("--fused-ce", action="store_true",
                        help="add @fused_lm_ce(enabled=true, ...) to the train block — the\n"
                             "[rows, vocab] logits are then never materialized (GEMM-chunked\n"
                             "fused loss)")
    args = parser.parse_args()

    if not args.nsl.exists():
        sys.exit(f"compiler not found at {args.nsl} — build with: cargo build --release --features cuda --bin nsl")
    if not args.tokens.exists():
        sys.exit(f"token stream not found at {args.tokens}")

    env_extra = dict(kv.split("=", 1) for kv in args.env)
    shape = ModelShape()
    gpu_name = args.gpu_name or detect_gpu_name()
    if gpu_name not in PEAK_TFLOPS_BY_DEVICE:
        known = "\n  ".join(sorted(PEAK_TFLOPS_BY_DEVICE))
        sys.exit(
            f"no peak-TFLOPS entry for GPU {gpu_name!r} — an MFU% against the wrong\n"
            f"roofline is worse than none. Add the device to PEAK_TFLOPS_BY_DEVICE\n"
            f"(measure with a cuBLAS GemmEx probe, not the marketing number) or pass\n"
            f"--gpu-name. Known devices:\n  {known}"
        )
    peak = PEAK_TFLOPS_BY_DEVICE[gpu_name][args.precision] * 1e12
    results = []

    print(f"model: {shape.matmul_params() / 1e6:.2f}M matmul params, "
          f"{shape.flops_per_token(args.seq_len) / 1e6:.1f} MFLOP/token (fwd+bwd, seq={args.seq_len})")
    print(f"device: {gpu_name}")
    print(f"device peak ({args.precision}): {peak / 1e12:.1f} TFLOPS dense\n")
    print(f"{'batch':>6} {'tok/cb':>9} {'ms/cb':>9} {'tok/s':>10} {'TFLOPS':>8} {'MFU':>7}")

    for batch_size in args.batch_sizes:
        program = build_program(
            args.model_dir, args.tokens.resolve(), batch_size, args.seq_len, args.grad_clip,
            args.extra_train_args, args.grad_accum, args.fused_ce, shape,
        )
        deltas, output = run_once(args.nsl, program, env_extra, args.timeout,
                                  args.max_steps, args.flags.split())
        if len(deltas) < 4:
            tail = "\n".join(output.strip().splitlines()[-12:])
            print(f"{batch_size:>6}  FAILED (only {len(deltas)} step intervals)\n{tail}\n")
            results.append({"batch_size": batch_size, "ok": False, "output_tail": tail})
            continue

        # Drop the first half: early steps carry warmup, allocator growth and
        # cold clocks, which on this card swing single-step timings ~10x.
        steady = deltas[len(deltas) // 2:]
        # Each callback fires every 1 step in the generated program.
        ms = statistics.median(steady) * 1000.0
        # on_step fires once per MICRO-batch, not once per optimizer step —
        # verified by running a 65,536-token epoch at batch=1/seq=1024 with
        # grad_accumulation=8 and counting 64 callbacks, not 8. Multiplying by
        # grad_accum here would inflate throughput by exactly that factor.
        tokens_per_callback = batch_size * args.seq_len
        tok_s = tokens_per_callback / (ms / 1000.0)
        achieved = tok_s * shape.flops_per_token(args.seq_len)
        mfu = achieved / peak

        print(f"{batch_size:>6} {tokens_per_callback:>9} {ms:>9.2f} {tok_s:>10.0f} "
              f"{achieved / 1e12:>8.2f} {mfu * 100:>6.1f}%")
        results.append({
            "label": args.label,
            "batch_size": batch_size,
            "seq_len": args.seq_len,
            "tokens_per_callback": tokens_per_callback,
            "grad_accum": args.grad_accum,
            "ms_per_step": ms,
            "tokens_per_s": tok_s,
            "achieved_tflops": achieved / 1e12,
            "mfu": mfu,
            "precision": args.precision,
            "gpu": gpu_name,
            "peak_tflops": peak / 1e12,
            "ok": True,
        })

    if args.json_out:
        args.json_out.write_text(json.dumps(results, indent=2), encoding="utf-8")


if __name__ == "__main__":
    main()
