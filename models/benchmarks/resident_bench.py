#!/usr/bin/env python3
"""Throughput A/B for the fully-resident 1B path (next-roadmap item 1).

Item 11 (PR #524) made the fully-resident 1B configuration COMPLETE —
optimizer moments on device, no `--optim-state-offload` — and items 11/12
recorded its memory posture to the byte. What was never measured is
THROUGHPUT: the resident-vs-offload step-time comparison does not exist
anywhere in the repo. This driver measures it, plus the geometry sweep
B2/A4, B4/A2, B8/A1 at the SAME 16,384 effective tokens per optimizer
update, in the production posture (`pretrain_prod.nsl`'s):

    nsl build --source-ad --checkpoint-blocks --fuse-rmsnorm-backward
              [--optim-state-offload]
    grad_clip=1.0, AdamW + warmup_cosine, @fused_lm_ce

Recorded per arm: tok/s (wall between steady-state loss-line arrivals — the
cadence-independent p0_campaign method), MFU against the measured tf32
roofline, the ACTUAL allocator peak + at-peak surface decomposition (the
program's own epilogue, not a step-boundary sample — that mistake is
documented twice over), the per-step allocated-bytes series from NSL_EVENTS
(exact bytes, every step), driver-level peak (nvidia-smi, a lower bound),
PCIe h2d/d2h (host-profile counters + dmon sampler), the fwd/bwd/opt phase
split, and a kernel breakdown (--profile-kernels Chrome trace) for the
headline pair.

Discipline (matrix_bench's, the PR #454 lesson): every arm is BUILT first,
then timing rounds run interleaved round-robin and each arm reports its best
round; instrumented passes (host-profile / phase-timing / kernel-profile)
are SEPARATE runs whose step times are discarded — timing with the
instrumentation on measures the instrumentation.

Geometry notes from the record: B8/A1 cannot run any --layerwise-accum arm
(accum >= 2 required), which is why the sweep lives in the prod posture; the
resident B8 cell is expected near the OOM boundary (~16.02 GiB persistent +
~8x the per-microbatch activation surface) — an OOM there is a RESULT, and
the events tail still yields the peak-at-failure.

Usage (from models/benchmarks/):
    python3 resident_bench.py --out /path/on/real/disk [--rounds 3]
        [--opt-steps 30] [--arms resident_b2a4,offload_b2a4,...]
"""

from __future__ import annotations

import argparse
import dataclasses
import json
import shutil
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_tokens  # noqa: E402
import gpu_guard  # noqa: E402
from matrix_bench import PEAK_TFLOPS_BY_DEVICE, SCALES  # noqa: E402
from p0_campaign import GpuSampler  # noqa: E402

REPO = Path(__file__).resolve().parents[2]
CODER1B = REPO / "models/coder1b"
SEQ = 2048
VOCAB = 49152
HIDDEN = 2048
TOKENS_PER_UPDATE = 16384

# The prod posture, verbatim from models/coder1b/pretrain_prod.nsl's run
# line. --optim-state-offload is THE axis under test; everything else held.
BASE_FLAGS = ["--source-ad", "--checkpoint-blocks", "--fuse-rmsnorm-backward"]

TEMPLATE = """\
# GENERATED by models/benchmarks/resident_bench.py — do not commit.
# The pretrain_prod.nsl posture minus checkpointing and validation: pure
# steady-state training throughput. Fused-CE hints and reshape dims are
# compile-time literals (a runtime logits.shape read refuses the fusion).
from model import NSLCoder
from nsl.nn.losses import cross_entropy

let m = NSLCoder()
m.to(cuda)

let tokens = load_mmap("TOKENS_PATH", 3)
let loader = DataLoader(tokens, batch_size=MICRO_BATCH, seq_len=2048, shuffle=true, drop_last=true)

print("LOSS_STREAM_BEGIN")

@fused_lm_ce(enabled=true, vocab_size=49152, hidden_size=2048, batch_size=MICRO_BATCH, seq_len=2048)
train(model=m, epochs=1, grad_accumulation=ACCUM, grad_clip=1.0):
    optimizer: AdamW(lr=0.0001, weight_decay=0.1, beta1=0.9, beta2=0.95, eps=1e-8)
    scheduler: warmup_cosine(warmup_steps=WARMUP_MICRO, total_steps=TOTAL_MICRO, min_lr=0.00003)
    step(batch):
        let logits = m.forward_train(batch.input_ids, true)
        let flat_logits = logits.reshape([FLAT_ROWS, 49152])
        let flat_labels = batch.labels.reshape([FLAT_ROWS])
        let loss = cross_entropy(flat_logits, flat_labels)
    callbacks:
        on_step(step, loss):
            if step % ACCUM == 0:
                print("OPT_STEP")
                print(step)
                print(loss)

print("LOSS_STREAM_END")

print("PEAK_BYTES")
print(gpu_peak_bytes())
print("PEAK_WEIGHTS")
print(gpu_surface_at_peak_bytes(1))
print("PEAK_OPTIM_M")
print(gpu_surface_at_peak_bytes(2))
print("PEAK_OPTIM_V")
print(gpu_surface_at_peak_bytes(3))
print("PEAK_M_PARTIAL")
print(gpu_surface_at_peak_bytes(4))
print("PEAK_ACTIVATIONS")
print(gpu_surface_at_peak_bytes(6))
print("RESIDENT_BENCH_COMPLETE")
"""


@dataclasses.dataclass
class Arm:
    key: str
    offload: bool
    micro_batch: int
    accum: int

    @property
    def flags(self) -> list[str]:
        return BASE_FLAGS + (["--optim-state-offload"] if self.offload else [])


ARMS = [
    Arm("resident_b2a4", False, 2, 4),
    Arm("offload_b2a4", True, 2, 4),
    Arm("resident_b4a2", False, 4, 2),
    Arm("offload_b4a2", True, 4, 2),
    Arm("resident_b8a1", False, 8, 1),
    Arm("offload_b8a1", True, 8, 1),
]


@dataclasses.dataclass
class RoundResult:
    tok_s: float
    wall_s: float
    opt_steps_measured: int


@dataclasses.dataclass
class ArmResult:
    arm: Arm
    oom: bool = False
    error: str | None = None
    rounds: list[RoundResult] = dataclasses.field(default_factory=list)
    peak_bytes: int | None = None
    surfaces: dict[str, int] = dataclasses.field(default_factory=dict)
    alloc_series: list[int] = dataclasses.field(default_factory=list)
    driver_peak_mb: float | None = None
    pcie_h2d_mib: float | None = None
    pcie_d2h_mib: float | None = None
    pcie_rx_peak: float | None = None
    pcie_tx_peak: float | None = None
    phase_fwd_s: float = 0.0
    phase_bwd_s: float = 0.0
    phase_opt_s: float = 0.0
    fused_lce_live: bool = False

    @property
    def best(self) -> RoundResult | None:
        return max(self.rounds, key=lambda r: r.tok_s) if self.rounds else None


def build_arm(arm: Arm, workdir: Path, tokens_path: Path, opt_steps: int,
              nsl: Path, phase_timing: bool = False) -> Path:
    """Generate the program, copy model/config beside it, `nsl build` once.

    `phase_timing` builds the Pass-B twin: NSL_PHASE_TIMING is read at
    COMPILE time (stmt.rs bakes the sync+print instrumentation into the
    binary), so the timing binary and the instrumented binary are different
    artifacts — which is exactly why Pass A must never run this one.
    """
    d = workdir / arm.key
    d.mkdir(parents=True, exist_ok=True)
    for f in ("model.nsl", "config.nsl"):
        shutil.copy2(CODER1B / f, d / f)
    total_micro = opt_steps * arm.accum
    prog = (
        TEMPLATE
        .replace("TOKENS_PATH", str(tokens_path))
        .replace("MICRO_BATCH", str(arm.micro_batch))
        .replace("ACCUM", str(arm.accum))
        .replace("WARMUP_MICRO", str(2 * arm.accum))
        .replace("TOTAL_MICRO", str(total_micro))
        .replace("FLAT_ROWS", str(arm.micro_batch * SEQ))
    )
    src = d / "bench.nsl"
    src.write_text(prog)
    binary = d / ("prog_phase" if phase_timing else "prog")
    import os
    env = dict(os.environ)
    env.setdefault("NSL_STDLIB_PATH", str(REPO / "stdlib"))
    if phase_timing:
        env["NSL_PHASE_TIMING"] = "1"
    r = subprocess.run(
        [str(nsl), "build", *arm.flags, str(src), "-o", str(binary)],
        cwd=d, capture_output=True, text=True, timeout=1800, env=env,
    )
    (d / "build_stderr.txt").write_text(r.stderr)
    if r.returncode != 0:
        raise RuntimeError(f"{arm.key}: build failed:\n{r.stderr[-2000:]}")
    # The fused-CE route is decided by CODEGEN and lands in the BUILD stderr
    # (review finding: the old runtime-stderr check could never be true). A
    # silent fallback ("will NOT run") would benchmark an unfused binary at a
    # 768 MiB/step handicap — refuse the arm instead of timing it.
    if "[fused-lce] forward route=" not in r.stderr or "will NOT run" in r.stderr:
        raise RuntimeError(
            f"{arm.key}: fused LM-CE did not engage at build time — refusing "
            f"to benchmark an unfused binary:\n{r.stderr[-2000:]}"
        )
    return binary


OOM_MARKERS = ("CUDA_ERROR_OUT_OF_MEMORY", "VRAM free", "Requested:", "out of memory")


def run_binary(binary: Path, env: dict[str, str], timeout: int,
               log: Path) -> tuple[int, list[tuple[float, str]]]:
    """Run, stamping each stdout line's arrival time (the tok/s clock).

    The stamped lines are PERSISTED beside the stderr log (review finding:
    the arrival stamps are the entire basis of the headline number and were
    being discarded). The watchdog is a timer, not an in-loop check — a
    binary that stops printing would otherwise block the read forever.
    """
    import os
    import threading
    full = dict(os.environ)
    full.setdefault("NSL_STDLIB_PATH", str(REPO / "stdlib"))
    full.update(env)
    lines: list[tuple[float, str]] = []
    with log.open("w") as lf:
        p = subprocess.Popen(
            [str(binary)], cwd=binary.parent, env=full,
            stdout=subprocess.PIPE, stderr=lf, text=True,
        )
        assert p.stdout is not None
        watchdog = threading.Timer(timeout, p.kill)
        watchdog.start()
        try:
            for line in p.stdout:
                lines.append((time.monotonic(), line.rstrip("\n")))
        finally:
            watchdog.cancel()
            p.wait()
    stamped = log.with_suffix(".stdout")
    stamped.write_text("".join(f"{t:.6f}\t{s}\n" for t, s in lines))
    return p.returncode, lines


def parse_timing(lines: list[tuple[float, str]], arm: Arm,
                 warmup_opt_steps: int) -> RoundResult | None:
    """tok/s over the steady-state window: OPT_STEP arrival stamps after
    warmup. Cadence-independent — tokens are counted, not inferred."""
    stamps = [t for t, s in lines if s == "OPT_STEP"]
    if len(stamps) <= warmup_opt_steps + 2:
        return None
    window = stamps[warmup_opt_steps:]
    wall = window[-1] - window[0]
    steps = len(window) - 1
    if wall <= 0 or steps == 0:
        return None
    return RoundResult(
        tok_s=steps * TOKENS_PER_UPDATE / wall, wall_s=wall, opt_steps_measured=steps
    )


def parse_epilogue(lines: list[tuple[float, str]], res: ArmResult) -> None:
    text = [s for _, s in lines]
    def after(marker: str) -> int | None:
        try:
            return int(float(text[text.index(marker) + 1]))
        except (ValueError, IndexError):
            return None
    res.peak_bytes = after("PEAK_BYTES")
    for marker, key in [("PEAK_WEIGHTS", "weights"), ("PEAK_OPTIM_M", "optim_m"),
                        ("PEAK_OPTIM_V", "optim_v"), ("PEAK_M_PARTIAL", "m_partial"),
                        ("PEAK_ACTIVATIONS", "activations")]:
        v = after(marker)
        if v is not None:
            res.surfaces[key] = v


def parse_events(events_file: Path, res: ArmResult) -> None:
    """allocated_bytes per step — exact bytes, every step (item 17). Tolerant
    parse: int(v) on arbitrary fields is the brittleness class the stream
    exists to kill."""
    if not events_file.exists():
        return
    series: dict[int, int] = {}
    for line in events_file.read_text().splitlines():
        try:
            ev = json.loads(line)
        except json.JSONDecodeError:
            continue
        if ev.get("kind") != "gpu_mem_step":
            continue
        step, v = ev.get("step"), ev.get("fields", {}).get("allocated_bytes")
        if isinstance(step, int) and isinstance(v, int):
            # First event carrying step k is the post-cleanup END event of
            # micro k-1 (steps 0 and last emit once; interior steps twice).
            series.setdefault(step, v)
    res.alloc_series = [series[k] for k in sorted(series)]


def parse_host_profile(stderr_text: str, stdout_lines: list[str],
                       res: ArmResult) -> None:
    import re
    m = None
    for m in re.finditer(r"pcie\s+h2d=([0-9.]+) MiB\s+d2h=([0-9.]+) MiB", stderr_text):
        pass  # LAST interval: excludes the one-time model upload
    if m:
        res.pcie_h2d_mib, res.pcie_d2h_mib = float(m.group(1)), float(m.group(2))
    # [phase] lines go to STDOUT, seconds without a unit suffix (math.rs).
    phase_re = re.compile(r"\[phase\] (?:fwd=([0-9.]+) bwd=([0-9.]+)|opt=([0-9.]+))")
    for line in stdout_lines:
        pm = phase_re.search(line)
        if not pm:
            continue
        if pm.group(3) is not None:
            res.phase_opt_s += float(pm.group(3))
        else:
            res.phase_fwd_s += float(pm.group(1))
            res.phase_bwd_s += float(pm.group(2))
    res.fused_lce_live = "[fused-lce] forward route=" in stderr_text


def kernel_breakdown(profile_json: Path, top: int = 12) -> list[tuple[str, float, int]]:
    """Top kernels by total duration from the --profile-kernels Chrome trace."""
    if not profile_json.exists():
        return []
    data = json.loads(profile_json.read_text())
    events = data.get("traceEvents", data if isinstance(data, list) else [])
    agg: dict[str, tuple[float, int]] = {}
    for ev in events:
        if not isinstance(ev, dict) or "dur" not in ev:
            continue
        name = ev.get("name", "?")
        tot, n = agg.get(name, (0.0, 0))
        agg[name] = (tot + float(ev["dur"]), n + 1)
    ranked = sorted(agg.items(), key=lambda kv: -kv[1][0])[:top]
    return [(name, tot / 1e6, n) for name, (tot, n) in ranked]  # us -> s


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, required=True,
                    help="workdir on REAL DISK (evidence outlives /tmp)")
    ap.add_argument("--nsl", type=Path,
                    default=REPO / "target/release/nsl")
    ap.add_argument("--rounds", type=int, default=3)
    ap.add_argument("--opt-steps", type=int, default=30)
    ap.add_argument("--warmup-opt-steps", type=int, default=10)
    ap.add_argument("--timeout", type=int, default=1800)
    ap.add_argument("--arms", type=str, default=",".join(a.key for a in ARMS))
    ap.add_argument("--skip-kernel-profile", action="store_true")
    args = ap.parse_args()

    gpu_guard.acquire_or_refuse("resident_bench")

    want = set(args.arms.split(","))
    arms = [a for a in ARMS if a.key in want]
    unknown = want - {a.key for a in ARMS}
    if unknown:
        sys.exit(f"unknown arm(s): {sorted(unknown)}")

    device = subprocess.run(
        ["nvidia-smi", "--query-gpu=name", "--format=csv,noheader"],
        capture_output=True, text=True, check=True,
    ).stdout.strip().splitlines()[0]
    if device not in PEAK_TFLOPS_BY_DEVICE:
        sys.exit(f"no measured roofline for '{device}' — refusing to quote a wrong MFU")
    roofline = PEAK_TFLOPS_BY_DEVICE[device]["tf32"] * 1e12
    flops_per_token = SCALES["1b"].flops_per_token(SEQ)

    work = args.out.resolve()
    args.nsl = args.nsl.resolve()
    work.mkdir(parents=True, exist_ok=True)
    tokens_path = work / "bench_tokens.bin"
    n_tokens = args.opt_steps * TOKENS_PER_UPDATE + 8 * SEQ  # slack for drop_last
    if not tokens_path.exists() or tokens_path.stat().st_size != n_tokens * 2:
        gen_tokens.generate(tokens_path, n_tokens, VOCAB, TOKENS_PER_UPDATE)

    # ── build every arm FIRST (interleaving discipline) ──────────────────
    results = {a.key: ArmResult(arm=a) for a in arms}
    binaries: dict[str, Path] = {}
    for a in arms:
        print(f"[build] {a.key}", flush=True)
        binaries[a.key] = build_arm(a, work, tokens_path, args.opt_steps, args.nsl)

    # ── Pass A: timing rounds, round-robin, events-only instrumentation ──
    for rnd in range(args.rounds):
        for a in arms:
            res = results[a.key]
            if res.oom or res.error:
                continue
            d = binaries[a.key].parent
            events = d / f"events_r{rnd}.jsonl"
            events.unlink(missing_ok=True)
            rc, lines = run_binary(
                binaries[a.key], {"NSL_EVENTS": str(events)},
                args.timeout, d / f"run_r{rnd}.stderr",
            )
            if rc != 0:
                stderr_text = (d / f"run_r{rnd}.stderr").read_text()
                parse_events(events, res)  # last step-boundary sample (NOT peak-at-failure)
                if any(m in stderr_text for m in OOM_MARKERS):
                    res.oom = True
                    print(f"[round {rnd}] {a.key}: OOM (a result, not a failure)", flush=True)
                else:
                    res.error = stderr_text[-800:]
                    print(f"[round {rnd}] {a.key}: FAILED rc={rc}", flush=True)
                continue
            timing = parse_timing(lines, a, args.warmup_opt_steps)
            if timing:
                res.rounds.append(timing)
                print(f"[round {rnd}] {a.key}: {timing.tok_s:,.0f} tok/s", flush=True)
            if rnd == 0:
                parse_epilogue(lines, res)
                parse_events(events, res)

    # ── Pass B: instrumented run per surviving arm (timings discarded).
    # Separate BUILD: NSL_PHASE_TIMING bakes sync+print into the binary.
    for a in arms:
        res = results[a.key]
        if res.oom or res.error:
            continue
        d = binaries[a.key].parent
        phase_bin = build_arm(a, work, tokens_path, args.opt_steps, args.nsl,
                              phase_timing=True)
        sampler = GpuSampler()
        sampler.start()
        rc, lines_b = run_binary(
            phase_bin,
            {"NSL_HOST_PROFILE": "1"},
            args.timeout, d / "run_instrumented.stderr",
        )
        sampler.stop()
        if rc == 0:
            parse_host_profile((d / "run_instrumented.stderr").read_text(),
                               [t for _, t in lines_b], res)
            if sampler.samples:
                res.driver_peak_mb = max(m.mem_mib for m in sampler.samples)
            if sampler.pcie:
                res.pcie_rx_peak = max(x.rx_mb_s for x in sampler.pcie)
                res.pcie_tx_peak = max(x.tx_mb_s for x in sampler.pcie)
        print(f"[instrumented] {a.key}: rc={rc}", flush=True)

    # ── Pass C: kernel breakdown for the headline pair ───────────────────
    kernels: dict[str, list[tuple[str, float, int]]] = {}
    if not args.skip_kernel_profile:
        for key in ("resident_b2a4", "offload_b2a4"):
            if key not in results or results[key].oom or results[key].error:
                continue
            d = binaries[key].parent
            prof = d / "kernel_profile.json"
            prof.unlink(missing_ok=True)
            # NSL_PROFILE_KERNELS=1 writes kernel_profile.json in the cwd
            # (the arm dir — run_binary sets cwd=binary.parent).
            rc, _ = run_binary(
                binaries[key], {"NSL_PROFILE_KERNELS": "1"},
                args.timeout, d / "run_kernels.stderr",
            )
            kernels[key] = kernel_breakdown(prof)
            print(f"[kernels] {key}: rc={rc}, {len(kernels[key])} kernels ranked", flush=True)

    # ── report ───────────────────────────────────────────────────────────
    git_rev = subprocess.run(
        ["git", "-C", str(REPO), "rev-parse", "HEAD"],
        capture_output=True, text=True,
    ).stdout.strip()
    out = {"device": device, "flops_per_token": flops_per_token,
           "roofline_tf32": roofline, "nsl_binary": str(args.nsl),
           "worktree_commit": git_rev, "arms": {}}
    # A partial --arms rerun must not clobber prior arms' results.
    prior = work / "results.json"
    if prior.exists():
        try:
            out["arms"] = json.loads(prior.read_text()).get("arms", {})
        except json.JSONDecodeError:
            pass
    print("\n| arm | tok/s (best) | MFU | peak GiB | activations GiB | "
          "optim on dev | pcie h2d/d2h MiB | fwd/bwd/opt s | alloc slope |")
    print("|---|---|---|---|---|---|---|---|---|")
    for a in arms:
        res = results[a.key]
        row: dict = {"oom": res.oom, "error": res.error}
        if res.oom:
            # The events tail is the last STEP-BOUNDARY sample, where
            # activations are ~0 by construction — it is NOT the allocated
            # bytes at failure (the abort's own NSL_MEMSTATS dump is; read
            # the run stderr). Label it as what it is.
            tail = (f"last step-boundary sample {res.alloc_series[-1]/2**30:.2f} GiB"
                    if res.alloc_series else "?")
            print(f"| {a.key} | OOM | — | {tail} | — | — | — | — | — |")
        elif res.best:
            b = res.best
            mfu = 100 * b.tok_s * flops_per_token / roofline
            peak = f"{res.peak_bytes/2**30:.2f}" if res.peak_bytes else "?"
            act = f"{res.surfaces.get('activations', 0)/2**30:.2f}"
            optim_dev = sum(res.surfaces.get(k, 0) for k in ("optim_m", "optim_v", "m_partial"))
            slope = "flat" if len(res.alloc_series) > 4 and \
                res.alloc_series[-1] == res.alloc_series[len(res.alloc_series)//2] else \
                (f"{(res.alloc_series[-1]-res.alloc_series[len(res.alloc_series)//2])/2**20:+.0f} MB" if res.alloc_series else "?")
            print(f"| {a.key} | {b.tok_s:,.0f} | {mfu:.1f}% | {peak} | {act} | "
                  f"{optim_dev/2**30:.1f} GiB | {res.pcie_h2d_mib or 0:.0f}/{res.pcie_d2h_mib or 0:.0f} | "
                  f"{res.phase_fwd_s:.0f}/{res.phase_bwd_s:.0f}/{res.phase_opt_s:.0f} | {slope} |")
            row.update(tok_s=b.tok_s, mfu_pct=mfu, wall_s=b.wall_s,
                       rounds=[dataclasses.asdict(r) for r in res.rounds])
        else:
            print(f"| {a.key} | no timing | — | — | — | — | — | — | — |")
        row.update(peak_bytes=res.peak_bytes, surfaces=res.surfaces,
                   driver_peak_mb=res.driver_peak_mb,
                   pcie_h2d_mib=res.pcie_h2d_mib, pcie_d2h_mib=res.pcie_d2h_mib,
                   pcie_rx_peak_mb_s=res.pcie_rx_peak, pcie_tx_peak_mb_s=res.pcie_tx_peak,
                       phase=[res.phase_fwd_s, res.phase_bwd_s, res.phase_opt_s],
                   fused_lce_live=res.fused_lce_live,
                   alloc_series_first_mid_last=(
                       [res.alloc_series[0], res.alloc_series[len(res.alloc_series)//2],
                        res.alloc_series[-1]] if res.alloc_series else None),
                   alloc_series_len=len(res.alloc_series))
        out["arms"][a.key] = row
    out["kernels"] = {k: [{"name": n, "total_s": t, "launches": c} for n, t, c in v]
                      for k, v in kernels.items()}
    (work / "results.json").write_text(json.dumps(out, indent=2))
    print(f"\nresults -> {work / 'results.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
